"""
04_merge_and_generate_tables.py
=================================
Run this LAST, after 01/02/03 have produced their JSON outputs. It generates
Markdown tables in the exact same format as Appendix C's existing tables, so
you can drop them straight into the thesis / paper, replacing the old N=8 /
single-seed tables.

Usage:
    python 04_merge_and_generate_tables.py \
        --ablation_dir results/ablation_b1_b4 \
        --extended_dir results/extended_n \
        --s3s4_dir results/multiseed_s3_s4 \
        --out publication_tables.md
"""
import argparse
import json
import os
import numpy as np
from scipy import stats


def load(path):
    if not os.path.exists(path):
        return None
    with open(path) as f:
        return json.load(f)


def table_ablation(ablation_dir):
    archetypes = ["residential", "office", "commercial", "mixed_use"]
    lines = ["### Table C.13 (NEW) — Full B1-B4 ablation, multi-seed, full training budget\n",
             "| Archetype | B1 Rule-Based | B2 Independent DDPG | B3 FedAvg (no pers.) | B4 Centralised Oracle | PFDRL (this work) |",
             "|---|---|---|---|---|---|"]
    for a in archetypes:
        data = load(os.path.join(ablation_dir, f"{a}_ablation.json"))
        if not data:
            lines.append(f"| {a} | *pending* | *pending* | *pending* | *pending* | *pending* |")
            continue
        row = [a]
        for b in ["B1", "B2", "B3", "B4"]:
            vals = np.array(data.get(b, []))
            row.append(f"{vals.mean():.3f} (±{vals.std():.3f})" if len(vals) else "*pending*")
        row.append("*copy from Appendix C.12*")
        lines.append("| " + " | ".join(row) + " |")
    lines.append("\n*Interpretation guide:* PFDRL vs B2 isolates the federation "
                  "benefit; PFDRL vs B3 isolates the personalisation benefit; "
                  "PFDRL vs B4 shows the (expected) gap to the privacy-inadmissible "
                  "ceiling. This directly resolves Limitation L9.\n")
    return "\n".join(lines)


def table_extended_h4(extended_dir, n_target):
    archetypes = ["residential", "office", "commercial", "mixed_use"]
    bonferroni_alpha = 0.05 / len(archetypes)
    lines = [f"### Table C.9 (UPDATED) — Wilcoxon signed-rank, FedProx vs FedAvg, N={n_target}\n",
             "| Archetype | p-value (N=8, old) | p-value (N={}, new) | Bonferroni survives? |".format(n_target),
             "|---|---|---|---|"]
    old_p = {"residential": 0.1484, "office": 1.0000, "commercial": 0.4609, "mixed_use": 0.3125}
    for a in archetypes:
        data = load(os.path.join(extended_dir, f"{a}_h4_N{n_target}.json"))
        if not data or len(data.get("seeds", [])) < n_target:
            lines.append(f"| {a} | {old_p[a]:.4f} | *pending* | *pending* |")
            continue
        diffs = np.array(data["seeds"])
        _, p = stats.wilcoxon(diffs)
        survives = "**YES**" if p < bonferroni_alpha else "no"
        lines.append(f"| {a} | {old_p[a]:.4f} | {p:.4f} | {survives} |")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--ablation_dir", default="results/ablation_b1_b4")
    parser.add_argument("--extended_dir", default="results/extended_n")
    parser.add_argument("--s3s4_dir", default="results/multiseed_s3_s4")
    parser.add_argument("--n_target", type=int, default=20)
    parser.add_argument("--out", default="publication_tables.md")
    args = parser.parse_args()

    sections = [
        "# Publication-Ready Tables — Enhanced Statistical Campaign\n",
        "Generated by 04_merge_and_generate_tables.py. Paste directly into "
        "the thesis Appendix C and the journal manuscript's Results section.\n",
        table_ablation(args.ablation_dir),
        "\n---\n",
        table_extended_h4(args.extended_dir, args.n_target),
    ]

    with open(args.out, "w") as f:
        f.write("\n".join(sections))
    print(f"Written: {args.out}")
    print("Review for any '*pending*' cells — these mean that script hasn't "
          "finished/run yet for that cell.")


if __name__ == "__main__":
    main()
